def generate_report(vulnerability: Dict[str, Any], template: str = 'generic') -> str:
    """
    Convenience function to generate a report.
    
    Args:
        vulnerability: Vulnerability details
        template: Template name
        
    Returns:
        Generated report
    """
    generator = ReportGenerator()
